"""Skilling UC1–UC75: attributed component seeds and finite symmetry orbits."""

from copy import deepcopy
from functools import lru_cache
import json
import math
from pathlib import Path
import re
import uuid
import numpy as np
from scipy.spatial import cKDTree

from .add_dual import PALETTE
from .compound_catalog import rotation
from .geometry import GeometryError, TOLERANCE, identity, validate

VERSION = '0.1.0'
DATA = Path(__file__).resolve().parent / 'catalog_data/uniform_compounds.json'
REFERENCE = 'https://www.antiprism.com/examples/150_named_models/540_uniform_compounds/imagelist.html'
ROTATIONAL = (1, 2, 7, 10, 11, 13, 20, 22, 24, 26, 28)
NAMESPACE = uuid.UUID('f631b467-a62c-4b10-b70e-af04c59c2b09')


@lru_cache(maxsize=1)
def definitions():
    return json.loads(DATA.read_text(encoding='utf-8'))


def _entry(uc):
    if type(uc) is not int or not 1 <= uc <= 75:
        raise GeometryError('Uniform compound number must be an integer from 1 to 75.')
    return definitions()['entries'][uc - 1]


def _component_name(entry):
    name = entry['name'].split(' ', 1)[1].removesuffix(' rotational')
    name = re.sub(r' [12]$', '', name)
    for plural, singular in (('hedra', 'hedron'), ('cubes', 'cube'), ('prisms', 'prism')):
        if name.endswith(plural):
            name = name[: -len(plural)] + singular
            break
    return name if not 20 <= entry['uc'] <= 25 else ('n/d-gonal prism' if entry['uc'] <= 21 else 'n/d-gonal antiprism')


def uniform_compound_catalog():
    records = []
    for e in definitions()['entries']:
        uc = e['uc']
        group = definitions()['groups'][e['group']]
        chiral = all(np.linalg.det(g) > 0 for g in group)
        records.append(
            {
                'key': f'compound-uc{uc}',
                'name': f'UC{uc}: ' + e['name'],
                'dimension': 3,
                'family': 'Compounds',
                'aliases': [f'UC{uc}', f'UC {uc}', f'UC-{uc}', e['name'], _component_name(e)],
                'ucNumber': uc,
                'counts': deepcopy(e['counts']),
                'componentCount': e['componentCount'],
                'componentPolyhedron': _component_name(e),
                'symmetryGroup': e['group'],
                'chiral': chiral,
                'chirality': 'numerically chiral' if chiral else 'numerically achiral',
                'uniform': True,
                'vertexTransitive': True,
                'source': 'generated by symmetry from attributed component seed',
                'vertexTransitivityScope': 'Geometric vertex sites; separate coincident constituent occurrences need not form one orbit.',
                'generatorFamily': {'kind': 'uniform-compound', 'uc': uc, **deepcopy(e['parameters'])},
                'freeAngle': uc in ROTATIONAL,
                'parameterizedPolygon': 20 <= uc <= 25,
                'reference': REFERENCE,
                'numericContract': 'Attributed float64 component seed and finite orthogonal orbit; no exact certificate',
            }
        )
    return records


@lru_cache(maxsize=8)
def _closure(name):
    group = np.asarray(definitions()['groups'][name])
    tree = cKDTree(group.reshape(len(group), 9))
    residual = max(float(max(tree.query((group @ g).reshape(len(group), 9))[0])) for g in group)
    if residual > 1e-10:
        raise GeometryError('Uniform compound generating group did not close.')
    return residual


def _key(points):
    return tuple(sorted(map(tuple, np.round(points, 8))))


def _orbit_matrices(points, group):
    seen = set()
    matrices = []
    for g in group:
        key = _key(points @ g.T)
        if key not in seen:
            seen.add(key)
            matrices.append(g)
    return matrices


def _prismatic(uc, n, d, k, angle):
    if any(type(x) is not int for x in (n, d, k)) or not 3 <= n <= 32 or not 2 <= k <= 12 or n * k > 128:
        raise GeometryError('UC20–UC25 require integer 3≤n≤32, 2≤k≤12 and n*k≤128.')
    if not 1 <= d < n or math.gcd(n, d) != 1:
        raise GeometryError('Polygon n/d must be reduced with 1≤d<n.')
    prism = uc in (20, 21)
    if prism and 2 * d >= n:
        raise GeometryError('Prism compounds support 0<d<n/2.')
    if not prism and (d % 2 != (1 if uc in (22, 23) else 0)):
        raise GeometryError('UC22/UC23 require odd d; UC24/UC25 require even d.')
    if not prism and 3 * d >= 2 * n:
        raise GeometryError('Uniform antiprism requires 3*d<2*n for a real positive height.')
    radius = 1 / (2 * math.sin(math.pi * d / n))
    half = math.pi * d / (2 * n)
    height = 1 if prism else math.sqrt(1 - (2 * radius * math.sin(half)) ** 2)
    points = np.asarray(
        [
            [radius * math.cos(-math.tau * i * d / n + phase), radius * math.sin(-math.tau * i * d / n + phase), z]
            for phase, z in ((0 if prism else half, height / 2), (0 if prism else -half, -height / 2))
            for i in range(n)
        ]
    )
    faces = [list(range(n)), list(range(2 * n - 1, n - 1, -1))]
    for i in range(n):
        j = (i + 1) % n
        faces.extend([[i, j, j + n, i + n]] if prism else [[i, j, i + n], [j, j + n, i + n]])
    order = n * k
    odd = uc in (22, 23) and k % 2 == 1
    horizontal = np.diag([1, 1, -1])
    flip = np.diag([1, -1, -1])
    mirror = rotation([0, 0, 1], -math.pi / order) @ np.diag([1, -1, 1]) if odd else horizontal
    group = [
        rotation([0, 0, 1], math.tau * i / order) @ a @ b
        for i in range(order)
        for a in (np.eye(3), flip)
        for b in (np.eye(3), mirror)
    ]
    trial = points @ rotation([0, 0, 1], math.radians(17 if uc in ROTATIONAL else 0)).T
    matrices = _orbit_matrices(trial, group)
    expected = (2 if uc in ROTATIONAL else 1) * k
    if len(matrices) != expected:
        raise GeometryError('Prismatic compound orbit failed its constituent count check.')
    points = points @ rotation([0, 0, 1], math.radians(angle)).T
    return points, faces, matrices, group, f'D{order}' + ('d' if odd else 'h')


def uniform_compound(uc=1, angleDegrees=None, n=None, d=None, k=None):
    e = _entry(uc)
    defaults = e['parameters']
    rotational = uc in ROTATIONAL
    if angleDegrees is not None and not rotational:
        raise GeometryError(f'UC{uc} has no free rotation angle.')
    angle = defaults.get('angleDegrees', 0) if angleDegrees is None else angleDegrees
    if type(angle) not in (int, float) or not math.isfinite(angle) or not -360 <= angle <= 360:
        raise GeometryError('Compound angle must be finite degrees from -360 to 360.')
    params = {'uc': uc}
    closure = _closure(e['group'])
    if rotational:
        params['angleDegrees'] = float(angle)
    if 20 <= uc <= 25:
        n = defaults['n'] if n is None else n
        d = defaults['d'] if d is None else d
        k = defaults['k'] if k is None else k
        points, faces, matrices, group, group_name = _prismatic(uc, n, d, k, angle)
        params.update(n=n, d=d, k=k)
        component_name = f'{n}/{d}-gonal ' + ('prism' if uc <= 21 else 'antiprism')
    else:
        if any(x is not None for x in (n, d, k)):
            raise GeometryError('Polygon n/d and k parameters apply only to UC20–UC25.')
        points = np.asarray(e['vertices'])
        faces = e['faces']
        matrices = np.asarray(e['matrices'])
        if rotational:
            points = points @ rotation(e['angleAxis'], math.radians(angle - defaults['angleDegrees'])).T
        group = np.asarray(definitions()['groups'][e['group']])
        group_name = e['group']
        component_name = _component_name(e)
    name = f'UC{uc}: ' + e['name']
    if 20 <= uc <= 25:
        name = f'UC{uc}: {len(matrices)} {component_name}s'
    if rotational:
        name += f' (θ={angle:g}°)'
    result = {
        'id': '',
        'name': name,
        'dimension': 3,
        'embeddingDimension': 3,
        'interpretation': 'generalized-complex',
        'vertices': [],
        'edges': [],
        'faces': [],
        'cells': [],
        'components': [],
        'numeric': {'mode': 'float64-approximate', 'certified': False, 'tolerance': TOLERANCE},
        'metadata': {},
        'provenance': {
            'operation': 'uniform-compound',
            'algorithmVersion': VERSION,
            'parameters': params,
            'catalogKey': f'compound-uc{uc}',
            'catalogSource': {
                'provider': 'Antiprism',
                'version': '0.32',
                'key': f'antiprism-uc{uc}',
                'sha256': e['sha256'],
                'licenseFile': 'specialized/COPYING',
            },
            'generation': 'finite symmetry orbit of attributed component seed'
            if not 20 <= uc <= 25
            else 'analytic unit-edge polygonal rings and dihedral orbit',
        },
    }
    colors = []
    for i, g in enumerate(matrices):
        offset = len(result['vertices'])
        fstart = len(result['faces'])
        estart = len(result['edges'])
        fs = [[v + offset for v in (f if np.linalg.det(g) > 0 else f[::-1])] for f in faces]
        edges = sorted({tuple(sorted((a, b))) for f in fs for a, b in zip(f, f[1:] + f[:1])})
        result['vertices'].extend((points @ g.T).tolist())
        result['faces'].extend(fs)
        result['edges'].extend(map(list, edges))
        result['components'].append(
            {
                'id': '',
                'name': f'{i + 1}: {component_name}',
                'sourcePath': [],
                'maps': {
                    'vertices': list(range(offset, len(result['vertices']))),
                    'edges': list(range(estart, len(result['edges']))),
                    'faces': list(range(fstart, len(result['faces']))),
                    'cells': [],
                },
            }
        )
        colors.extend([{'encoding': 'byte', 'values': list(PALETTE[i % len(PALETTE)])} for _ in fs])
    fingerprint = identity(result)
    result['id'] = str(uuid.uuid5(NAMESPACE, fingerprint))
    for i, c in enumerate(result['components']):
        c.update(
            id=str(uuid.uuid5(NAMESPACE, fingerprint + ':' + str(i))),
            sourceModelId=result['id'],
            sourceFingerprint=fingerprint,
        )
    record = next(r for r in uniform_compound_catalog() if r['ucNumber'] == uc)
    record.update(
        counts=[len(result[x]) for x in ('vertices', 'edges', 'faces', 'cells')],
        componentCount=len(matrices),
        componentPolyhedron=component_name,
        symmetryGroup=group_name,
        generatorFamily={'kind': 'uniform-compound', **params},
    )
    record['offColors'] = {'faces': colors, 'cells': []}
    record['uniformCompound'] = {
        'schemaVersion': 1,
        'parameters': params,
        'representativeParameters': deepcopy(defaults),
        'componentMatrices': np.asarray(matrices).tolist(),
        'groupOrder': len(group),
        'properOrder': int(sum(np.linalg.det(g) > 0 for g in group)),
        'closureVerified': True,
        'closureResidual': closure if not 20 <= uc <= 25 else None,
        'closureMethod': 'numerical multiplication table'
        if not 20 <= uc <= 25
        else 'analytic cyclic/dihedral group construction',
        'angleAxis': e['angleAxis'],
        'referenceResidual': e['sourceResidual'],
        'distinctVertexCount': len(np.unique(np.round(result['vertices'], 8), axis=0)),
        'referenceScope': 'Default attributed representative only; ordered component face cycles and vertex residual normalized by RMS source radius.',
        'symmetryScope': 'Declared generating group; enhanced symmetry at special angles is not enumerated.',
        'seedSource': 'attributed Antiprism component decimals'
        if not 20 <= uc <= 25
        else 'analytic unit-edge polygonal rings',
        'coincidentPolicy': 'Separate constituent incidence retained, including coincident constituents at special angles.',
    }
    result['metadata'].update(record)
    result['validation'] = validate(result)
    if not result['validation']['passed']:
        raise GeometryError('Uniform compound failed incidence validation.')
    result['fingerprint'] = identity(result)
    result['metadata']['uniformCompound']['sourceFingerprint'] = result['fingerprint']
    return result


def load_uniform_compound(key):
    match = re.fullmatch(r'compound-uc([1-9][0-9]?)', key) if isinstance(key, str) else None
    return uniform_compound(int(match[1])) if match and int(match[1]) <= 75 else None
