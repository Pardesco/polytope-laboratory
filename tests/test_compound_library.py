def test_history_undo_redo_save_reload_replay_then_component_edit(tmp_path):
    source = regular('cube')
    source['metadata']['offColors'] = {'faces': [{'encoding': 'byte', 'values': [19, 37, 99, 188]}] * 6, 'cells': []}
    doc = {'id': 'history', 'cursor': 0, 'states': [{'model': source, 'view': {}, 'notes': 'Keep my notes'}]}
    result = dispatch({'op': 'recipe-run', 'params': {'document': doc, 'operation': 'add-dual', 'parameters': {}}})
    assert len(doc['states']) == 1
    assert len(result['states']) == 2 and result['cursor'] == 1
    result['cursor'] = 0
    assert result['states'][result['cursor']]['model'] == source
    result['cursor'] = 1
    compound = result['states'][1]['model']
    assert compound['metadata']['offColors']['faces'][:6] == source['metadata']['offColors']['faces']
    project = {'format': 'polytope-laboratory', 'version': 1, 'active': 0, 'documents': [result]}
    path = tmp_path / 'compound.polytope'
    save_project(path, project)
    restored = validate_project(json.loads(path.read_text(encoding='utf-8')))['documents'][0]
    assert restored['states'][1]['model']['components'] == compound['components']
    replayed = dispatch({'op': 'recipe-replay', 'params': {'document': restored}})
    replay_model = replayed['states'][0]['model']
    assert canonical_model(replay_model) == canonical_model(compound)
    assert replay_model['components'] == compound['components']
    assert replayed['states'][0]['notes'] == 'Keep my notes'
    selected = compound['components'][1]['id']
    edited = dispatch(
        {
            'op': 'recipe-run',
            'params': {
                'document': restored,
                'operation': 'compound-component',
                'parameters': {'component_id': selected},
            },
        }
    )
    replayed = dispatch({'op': 'recipe-replay', 'params': {'document': edited}})
    assert len(replayed['states'][0]['model']['vertices']) == 6
