VERSION='0.1.0'
REFERENCES=['https://johncarlosbaez.wordpress.com/2017/12/28/the-600-cell-part-3/',
            'https://en.wikipedia.org/wiki/600-cell#Twenty-five_24-cells',
            'https://en.wikipedia.org/wiki/Polytope_compound#4-polytope_compounds']
KINDS=('vertices','edges','faces','cells')
# A one-sided orbit is deliberately distinguished from the full H4 orbit.
ENTRIES=[
    ('two-16-cells','2 16-cells in the tesseract','B4','demicube',2,[8,24,32,16]),
    ('three-16-cells','3 16-cells in the 24-cell','F4','cross',3,[8,24,32,16]),
    ('three-tesseracts','3 tesseracts in the 24-cell','F4','cube',3,[16,32,24,8]),
    ('fifteen-16-cells','15 16-cells (left quaternion cosets)','2I-left','cross',15,[8,24,32,16]),
    ('fifteen-tesseracts','15 tesseracts (left quaternion orbit)','2I-left','cube',15,[16,32,24,8]),
    ('seventy-five-16-cells','75 inscribed 16-cells in the 600-cell','H4','cross',75,[8,24,32,16]),
    ('seventy-five-tesseracts','75 inscribed tesseracts in the 600-cell','H4','cube',75,[16,32,24,8]),
    ('twenty-five-24-cells','25 inscribed 24-cells in the 600-cell','H4','24',25,[24,96,96,24]),
]


def compound4_catalog():
    result=[]
    for key,name,group,seed,n,counts in ENTRIES:
        frame='tesseract' if group=='B4' else 'cell24' if group=='F4' else 'cell600'
        label={'B4':'[4,3,3]','F4':'[3,4,3]','H4':'[5,3,3]','2I-left':'2I-left'}[group]
        result.append({'key':'compound4-'+key,'name':'Compound of '+name,'dimension':4,'family':'4D compounds',
            'counts':[n*c for c in counts],'componentCount':n,'constituent':seed,'frameKey':frame,
            'aliases':[key.replace('-',' '),f'{n} '+('24 cells' if seed=='24' else 'tesseracts' if seed=='cube' else '16 cells'),
                       'quaternion compound' if group in ('H4','2I-left') else 'symmetry compound'],
            'symmetryGroup':label,'symmetryGroups':[group],'convex':False,
            'compoundClassification':'specified symmetry orbit; no complete regular-compound classification',
            'source':'generated by symmetry','provenance':'generated by symmetry','referenceUrls':REFERENCES,
            'numericContract':'Analytic finite group construction evaluated in float64; no exact certificate'})
    for entry in result:
        if entry['key']!='compound4-fifteen-tesseracts':entry.update(uniform=True,vertexTransitive=True)
        if entry['key'] in ('compound4-three-16-cells','compound4-three-tesseracts'):
            entry.update(regular=True,compoundClassification='regular compound in the F4 frame')
    return result


def _unique(matrices):
    seen={}
    for g in matrices:seen.setdefault(tuple(np.round(g,8).ravel()),g)
    return np.asarray(list(seen.values()))


@lru_cache(maxsize=4)
def frame_group(name):
    points=vertices600();conjugate=np.diag([1,-1,-1,-1])
    left=np.asarray([quaternion_matrix(q) for q in points])
    # All 120 products against all 120 vertices check closure of 2I.
    residual=max(float(max(cKDTree(points).query(points@g.T)[0])) for g in left)
    if residual>1e-8:raise GeometryError('Binary icosahedral quaternion group did not close.')
    signed=np.asarray([np.eye(4)[list(p)]*np.asarray(s)[:,None] for p in permutations(range(4)) for s in product((-1,1),repeat=4)])
    if name=='B4':
        frame=np.asarray(list(product((-0.5,0.5),repeat=4)));group=signed
    elif name=='F4':
        frame=points[:24];group=_unique(a@b for a in left[:24] for b in signed)
    elif name=='2I-left':frame=points;group=left
    elif name=='H4':
        frame=points;right=[conjugate@g@conjugate for g in left]
        proper=_unique(a@b for a in left for b in right)
        group=np.concatenate([proper,proper@conjugate])
    else:raise GeometryError('Unsupported compound generating group.')
    order={'B4':384,'F4':1152,'2I-left':120,'H4':14400}[name]
    if len(group)!=order:raise GeometryError('Compound generating group has the wrong order.')
    distances,actions=cKDTree(frame).query(frame@group.transpose(0,2,1))
    residual=max(residual,float(distances.max()))
    if residual>1e-8 or any(len(set(p))!=len(frame) for p in actions):
        raise GeometryError('Compound frame action is not a resolved vertex bijection.')
    # Exhaust the generated action group, checking every generator transition.
    keys={tuple(p):i for i,p in enumerate(actions)};seen={keys[tuple(range(len(frame)))]};generators=[]
    for candidate in range(len(group)):
        if candidate in seen:continue
        generators.append(candidate);pending=deque(seen)
        while pending:
            i=pending.popleft()
            for j in generators:
                other=keys.get(tuple(actions[j][actions[i]]))
                if other is None:raise GeometryError('Compound frame action failed group closure.')
                if other not in seen:seen.add(other);pending.append(other)
        if len(seen)==order:break
    if len(seen)!=order:raise GeometryError('Compound group traversal was incomplete.')
    return frame,group,actions,{'group':name,'groupOrder':order,'closureVerified':True,'closureResidual':residual,
        'generatorMatrices':[group[i].tolist() for i in generators],
        'symmetryScope':'complete declared frame group' if name!='2I-left' else '120 left quaternion actions; not the full compound symmetry group'}


@lru_cache(maxsize=8)
def _build(key):
    entry=next((r for r in compound4_catalog() if r['key']==key),None)
    if entry is None:raise GeometryError('Unknown 4D compound key.')
    row=next(r for r in ENTRIES if key=='compound4-'+r[0]);group_name,seed=row[2:4]
    frame,group,actions,evidence=frame_group(group_name)
    points=vertices600()
    seed_points=points[:8] if seed=='cross' else points[8:24] if seed=='cube' else points[:24]
    if seed=='demicube':seed_points=np.asarray([p for p in frame if np.prod(p)>0])
    source=hull(seed_points,'24-cell' if seed=='24' else 'Tesseract' if seed=='cube' else '16-cell')
    _,seed_ids=cKDTree(frame).query(source['vertices']);seen=set();occurrences=set();models=[];transforms=[]
    for g,action in zip(group,actions):
        ids=action[seed_ids];signature=tuple(sorted(ids.tolist()))
        occurrences.add((signature,int(ids[0])))
        if signature in seen:continue
        seen.add(signature);part=moved(source,g)
        part['vertices']=frame[ids].tolist();part['fingerprint']=identity(part)
        part['id']=str(uuid.uuid5(uuid.NAMESPACE_URL,'polytope:compound4:'+part['fingerprint']))
        models.append(part);transforms.append(g.tolist())
    if len(models)!=entry['componentCount']:raise GeometryError('Compound orbit count differs from the documented construction.')
    result=assemble(models)
    counts=[len(result[k]) for k in KINDS]
    if counts!=entry['counts']:raise GeometryError('Compound incidence count differs from the registry.')
    if entry.get('vertexTransitive') and len(occurrences)!=counts[0]:
        raise GeometryError('Compound group did not act transitively on constituent-vertex occurrences.')
    distances,ids=cKDTree(frame).query(result['vertices']);multiplicity=Counter(ids.tolist())
    if len(multiplicity)!=len(frame) or len(set(multiplicity.values()))!=1 or max(distances)>1e-8:
        raise GeometryError('Compound does not cover its frame with constant vertex multiplicity.')
    result['name']=entry['name'];result['metadata'].update(deepcopy(entry))
    result['metadata']['compound4Evidence']={**evidence,'resultFingerprint':identity(result),'componentCount':len(models),
        'frameKey':entry['frameKey'],'distinctVertexCount':len(frame),'vertexMultiplicity':next(iter(multiplicity.values())),
        'verifiedVertexOccurrenceOrbitSize':len(occurrences),
        'frameVertexResidual':float(max(distances)),'frameActionResidual':evidence['closureResidual'],
        'componentMatrices':transforms,'certified':False,'coordinateTolerance':1e-8,
        'construction':'Finite orbit of one convex constituent; nearest frame IDs accepted only after bijection/residual checks. Coincident vertices retain separate incidence.'}
    result['provenance'].update(catalogKey=key,algorithmVersion=VERSION)
    result['fingerprint']=identity(result);result['validation']=validate(result)
    if not result['validation']['passed']:raise GeometryError('Constructed compound failed incidence validation.')
    return result


def load_compound4(key):return deepcopy(_build(key))
