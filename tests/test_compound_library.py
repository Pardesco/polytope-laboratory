def test_five_tetrahedra_enantiomers_have_distinct_parts_and_reflect_into_each_other():
    a, b = [load_compound_model('compound-five-tetrahedra-' + suffix) for suffix in ('a', 'b')]

    def keys(m, matrix):
        return {vertex_key(np.asarray(m['vertices'])[c['maps']['vertices']] @ matrix.T) for c in m['components']}

    assert keys(a, np.eye(3)) != keys(b, np.eye(3))
    assert keys(a, -np.eye(3)) == keys(b, np.eye(3))
    for g in symmetry_group('I'):
        assert keys(a, g) == keys(a, np.eye(3))
        assert keys(a, g) != keys(b, np.eye(3))


