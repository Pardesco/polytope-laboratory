contextBridge.exposeInMainWorld('polytope',{
  startupInfo:()=>ipcRenderer.invoke('startup-info'),
  onFullscreenChanged:callback=>{const listener=(_,value)=>callback(value);ipcRenderer.on('fullscreen-changed',listener);return ()=>ipcRenderer.removeListener('fullscreen-changed',listener);},
  recentFiles:()=>ipcRenderer.invoke('recent-files'),
  requestRecent:id=>ipcRenderer.invoke('request-recent',id),
  takeOpenRequest:()=>ipcRenderer.invoke('take-open-request'),
  discardOpenRequest:token=>ipcRenderer.invoke('discard-open-request',token),
  openRequested:(token,id)=>ipcRenderer.invoke('open-requested',token,id),
  confirmProjectOpen:()=>ipcRenderer.invoke('confirm-project-open'),
  onOpenAvailable:callback=>{const listener=()=>callback();ipcRenderer.on('open-available',listener);return ()=>ipcRenderer.removeListener('open-available',listener);},
  onRecentFilesChanged:callback=>{const listener=()=>callback();ipcRenderer.on('recent-files-changed',listener);return ()=>ipcRenderer.removeListener('recent-files-changed',listener);},
  engine:(request,id)=>ipcRenderer.invoke('engine',request,id),
  cancel:id=>ipcRenderer.invoke('cancel',id),
  open:id=>ipcRenderer.invoke('open',id), save:project=>ipcRenderer.invoke('save',project),
  autosave:project=>ipcRenderer.invoke('autosave',project), recover:id=>ipcRenderer.invoke('recover',id),
  recoveryInfo:()=>ipcRenderer.invoke('recovery-info'), setDirty:value=>ipcRenderer.invoke('dirty',value),
  setWorkspaceAvailability:value=>ipcRenderer.invoke('workspace-availability',value),
  discoveryMenu:name=>ipcRenderer.invoke('discovery-menu',name),
  importTour:()=>ipcRenderer.invoke('import-tour'),exportTour:tour=>ipcRenderer.invoke('export-tour',tour),
  export:(model,format)=>ipcRenderer.invoke('export',model,format),
  saveImage:data=>ipcRenderer.invoke('save-image',data),saveSvg:(svg,name)=>ipcRenderer.invoke('save-svg',svg,name),
  beginImageExport:(id,params)=>ipcRenderer.invoke('image-export-begin',id,params),
  writeImageExport:(id,data)=>ipcRenderer.invoke('image-export-write',id,data),
  abortImageExport:id=>ipcRenderer.invoke('image-export-abort',id),
  library:()=>ipcRenderer.invoke('library'),libraries:()=>ipcRenderer.invoke('libraries'),unlinkLibrary:path=>ipcRenderer.invoke('unlink-library',path),libraryModel:(path,id)=>ipcRenderer.invoke('library-model',path,id),
  attachLibraryAudit:path=>ipcRenderer.invoke('attach-library-audit',path),verifyLibraryAudit:path=>ipcRenderer.invoke('verify-library-audit',path),repairLibraryCopy:path=>ipcRenderer.invoke('repair-library-copy',path),
  animationBegin:options=>ipcRenderer.invoke('animation-begin',options),animationWrite:(id,index,data)=>ipcRenderer.invoke('animation-write',id,index,data),animationFinish:id=>ipcRenderer.invoke('animation-finish',id),animationAbort:id=>ipcRenderer.invoke('animation-abort',id),
  print:svg=>ipcRenderer.invoke('print',svg),saveNetPdf:svg=>ipcRenderer.invoke('save-net-pdf',svg),fullscreen:()=>ipcRenderer.invoke('fullscreen'),
  presentationWindow:enabled=>ipcRenderer.invoke('presentation-window',enabled),
  savePackedNetPdf:pages=>ipcRenderer.invoke('save-packed-net-pdf',pages),printPackedNets:pages=>ipcRenderer.invoke('print-packed-nets',pages),
  renderPackedNetPdf:pages=>ipcRenderer.invoke('render-packed-net-pdf',pages),
  beginNetPrint:(id,params)=>ipcRenderer.invoke('net-print-begin',id,params),
  commitNetPrint:id=>ipcRenderer.invoke('net-print-commit',id),
  abortNetPrint:id=>ipcRenderer.invoke('net-print-abort',id),
  beginTextExport:params=>ipcRenderer.invoke('text-export-begin',params),
  writeTextExport:(id,data)=>ipcRenderer.invoke('text-export-write',id,data),
  abortTextExport:id=>ipcRenderer.invoke('text-export-abort',id),
  beginGeometryExport:params=>ipcRenderer.invoke('geometry-export-begin',params),
  writeGeometryExport:(id,data)=>ipcRenderer.invoke('geometry-export-write',id,data),
  abortGeometryExport:id=>ipcRenderer.invoke('geometry-export-abort',id),
  onAction:callback=>{const listener=(_,name)=>callback(name);ipcRenderer.on('menu-action',listener);return ()=>ipcRenderer.removeListener('menu-action',listener);}
});
