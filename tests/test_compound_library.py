def point_key(point):
    return tuple(np.round(point, 7))


def boundary_key(model, matrix):
    points = [point_key(p) for p in np.asarray(model['vertices']) @ matrix.T]

    def cycle(ids):
        seq = [points[i] for i in ids]
        return min(tuple(s[i:] + s[:i]) for s in (seq, seq[::-1]) for i in range(len(s)))

    faces = [cycle(f) for f in model['faces']]
    return (
        tuple(sorted(points)),
        tuple(sorted(tuple(sorted(points[i] for i in e)) for e in model['edges'])),
        tuple(sorted(faces)),
        tuple(sorted(tuple(sorted(faces[i] for i in c)) for c in model['cells'])),
    )


@pytest.mark.parametrize(
    'record',
    [
        r
        for r in RECORDS
        if r.get('ucNumber')
        or r['key'] in ('compound-four-cubes', 'compound-three-octahedra', 'compound-five-24-cells')
    ],
    ids=lambda r: r['key'],
)
def test_generated_group_closes_component_incidence_and_uniform_vertex_orbit(record):
    m = load_compound_model(record['key'])
    info = m['metadata']['compoundSymmetry']
    if m['dimension'] == 4:
        group = [quaternion_matrix(q) for q in vertices600()]
    elif info['group'] == 'inversion':
        from engine.symmetry import geometric_symmetry

        seed = regular('snub-cube' if 'cubes' in record['key'] else 'snub-dodecahedron')
        proper = geometric_symmetry(seed, orientation='proper')
        assert proper['complete'] and proper['closureVerified']
        rotations = [np.asarray(a['matrix']) for a in proper['actions']]
        group = rotations + [-g for g in rotations]
    else:
        group = symmetry_group(info['group'])
    leaves = [extract_component(m, c['id']) for c in m['components']]
    original = {boundary_key(leaf, np.eye(m['dimension'])) for leaf in leaves}
    for g in group:
        assert {boundary_key(leaf, g) for leaf in leaves} == original
    if record.get('ucNumber'):
        # Actual geometric vertex transitivity, independently of constituent count.
        points = np.asarray(m['vertices'])
        tree = cKDTree(points)
        images = np.asarray([g @ points[0] for g in group])
        distances, _ = tree.query(images)
        assert max(distances) < 1e-7
        assert len(vertex_key(images)) >= len(set(vertex_key(points)))
        assert set(vertex_key(images)) == set(vertex_key(points))
        incidence_orbit = {
            (boundary_key(leaves[0], g), point_key(g @ np.asarray(leaves[0]['vertices'][0]))) for g in group
        }
        assert len(incidence_orbit) == len(m['vertices'])


@pytest.mark.parametrize('key', ['cube', 'octahedron', 'dodecahedron', 'icosahedron'])
def test_add_dual_edges_cross_every_primal_midpoint(key):
    source = transform(regular(key), matrix=[[0, -1, 0], [1, 0, 0], [0, 0, 1]], translation=[4, -3, 7], scale=2.5)
    original = copy.deepcopy(source)
    result = add_dual(source)
    assert source == original
    polar = extract_component(result, result['components'][1]['id'])
    vertices = np.asarray(polar['vertices'])
    for edge in source['edges']:
        midpoint = np.asarray(source['vertices'])[edge].mean(axis=0)
        hits = []
        primal_direction = np.diff(np.asarray(source['vertices'])[edge], axis=0)[0]
        for a, b in polar['edges']:
            direction = vertices[b] - vertices[a]
            t = (midpoint - vertices[a]) @ direction / (direction @ direction)
            if np.linalg.norm(vertices[a] + t * direction - midpoint) < 1e-7 and -1e-7 < t < 1 + 1e-7:
                hits.append(abs(float(direction @ primal_direction)))
        assert hits and min(hits) < 1e-7
    evidence = result['metadata']['addDual']
    assert max(evidence[k] for k in ('sphereResidual', 'midpointResidual', 'crossingResidual')) < 1e-7
    assert len(result['components']) == 2
    assert retrieve_source(result, 0)['vertices'] == source['vertices']


def test_4d_ridge_sizing_tesseract_counts_and_contact():
    result = add_dual(regular('tesseract'))
    assert [len(result[k]) for k in ('vertices', 'edges', 'faces', 'cells')] == [24, 56, 56, 24]
    assert result['metadata']['addDual']['radius'] == pytest.approx(np.sqrt(2))
    primal, polar = [extract_component(result, c['id']) for c in result['components']]
    q = np.asarray(polar['vertices'])
    for ridge in primal['faces']:
        contact = np.asarray(primal['vertices'])[ridge].mean(axis=0)
        assert any(np.linalg.norm(q[e].mean(axis=0) - contact) < 1e-7 for e in polar['edges'])


def test_explicit_reciprocation_for_no_midsphere_and_star_diagnoses():
    source = hull([[0, 0, 0], [3, 0, 0], [0, 2, 0], [0, 0, 1]])
    with pytest.raises(GeometryError, match='sphere'):
        add_dual(source)
    result = add_dual(source, sizing='reciprocal', center=[0.3, 0.3, 0.2], radius=2)
    assert len(result['components']) == 2
    assert 'no edge/ridge contact claim' in result['metadata']['addDual']['definition']
    source = regular('great-dodecahedron')
    with pytest.raises(GeometryError, match='convex'):
        add_dual(source)
    assert len(add_dual(source, sizing='reciprocal')['components']) == 2
    with pytest.raises(GeometryError, match='strictly inside'):
        add_dual(regular('cube'), sizing='reciprocal', center=[3, 0, 0])


