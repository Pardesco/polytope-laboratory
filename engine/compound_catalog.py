def rotation(axis, angle):
    a = np.asarray(axis, dtype=float); a /= np.linalg.norm(a)
    x,y,z = a
    skew = np.array([[0,-z,y],[z,0,-x],[-y,x,0]])
    return math.cos(angle)*np.eye(3)+(1-math.cos(angle))*np.outer(a,a)+math.sin(angle)*skew


@lru_cache(maxsize=4)
def symmetry_group(name):
    if name in ('O', 'Oh'):
        group = [np.eye(3)[list(p)]*np.asarray(s)[:,None] for p in permutations(range(3)) for s in product((-1,1),repeat=3)]
        return tuple(g for g in group if name == 'Oh' or np.linalg.det(g)>0)
    from .generators import regular
    from .symmetry import geometric_symmetry
    report = geometric_symmetry(regular('icosahedron'), orientation='proper' if name == 'I' else 'all')
    if not report['complete'] or not report['closureVerified'] or report['order'] != (60 if name=='I' else 120):
        raise GeometryError('Icosahedral generating group did not close.')
    return tuple(np.asarray(a['matrix']) for a in report['actions'])


def vertex_key(points):
    return tuple(sorted(tuple(row) for row in np.round(np.asarray(points), 8)))


def moved(source, matrix):
    # Change only the embedding; source cycles and cell incidence remain literal.
    result = deepcopy(source)
    result['vertices'] = (np.asarray(source['vertices']) @ matrix.T).tolist()
    if source['dimension']==3 and np.linalg.det(matrix)<0:
        result['faces'] = [list(reversed(f)) for f in result['faces']]
    for key in ('facetEquations','measure','rationalCoordinates','rationalFacetEquations','certificate'):
        result.pop(key, None)
    result['numeric'] = {**source['numeric'], 'mode':'float64-approximate','certified':False}
    result['fingerprint'] = identity(result)
    result['id'] = str(uuid.uuid5(uuid.NAMESPACE_URL, 'polytope:compound-image:'+result['fingerprint']))
    result['provenance'] = {'operation':'symmetry-image', 'algorithmVersion':VERSION,
                            'sourceModelId':source['id'], 'sourceFingerprint':identity(source),
                            'parameters':{'matrix':matrix.tolist()}}
    return result


def orbit_models(source, matrices, expected):
    seen = set(); models = []; transforms = []
    for matrix in matrices:
        points = np.asarray(source['vertices']) @ matrix.T
        key = vertex_key(points)
        if key not in seen:
            seen.add(key); models.append(moved(source, matrix)); transforms.append(matrix.tolist())
    if len(models) != expected:
        raise GeometryError(f'Compound orbit has {len(models)} constituents; expected {expected}.')
    return models, transforms


def assemble(models):
    models = [colored(m, i) for i,m in enumerate(models)]
    # A balanced source tree keeps component extraction paths and projects small.
    while len(models)>1:
        models = [add_models(models[i],models[i+1]) if i+1<len(models) else models[i] for i in range(0,len(models),2)]
    return models[0]


def quaternion_matrix(q):
    w,x,y,z = q
    return np.array([[w,-x,-y,-z],[x,w,-z,y],[y,z,w,-x],[z,-y,x,w]])


def five_24_cells():
    from .generators import vertices600
    all_points = vertices600()
    seed = hull(all_points[:24], '24-cell (Hurwitz vertices)')
    matrices = [quaternion_matrix(q) for q in all_points]
    tree = cKDTree(all_points)
    closure_residual = max(float(max(tree.query(all_points @ g.T)[0])) for g in matrices)
    if closure_residual>1e-7:
        raise GeometryError('Binary icosahedral quaternion multiplication did not close.')
    models, transforms = orbit_models(seed, matrices, 5)
    joined = np.concatenate([m['vertices'] for m in models])
    distances, ids = cKDTree(all_points).query(joined)
    if max(distances)>1e-7 or len(set(ids))!=120:
        raise GeometryError('The five 24-cells did not partition the 600-cell vertices.')
    return assemble(models), {'group':'left multiplication by binary icosahedral unit quaternions', 'groupOrder':120,
                              'componentMatrices':transforms, 'vertexPartitionResidual':float(max(distances)),
                              'distinctVertexCount':120, 'closureVerified':True, 'closureResidual':closure_residual,
                              'symmetryScope':'120 left quaternion actions; not a full symmetry enumeration'}


def load_compound_model(key):
    from .uniform_compounds import load_uniform_compound
    uniform = load_uniform_compound(key)
    if uniform is not None:return uniform
    entry = next((r for r in compound_catalog() if r['key']==key), None)
    if entry is None:return None
    from .generators import regular
    if key == 'compound-five-24-cells':
        result, evidence = five_24_cells()
    elif any(key=='compound-'+pair[0] for pair in PAIRS):
        pair = next(p for p in PAIRS if key=='compound-'+p[0])
        result = add_dual(regular(pair[2])); evidence = {'method':'polar dual at checked common edge/ridge sphere'}
    elif key == 'compound-great-dodecahedron-small-stellated':
        from .incidence_dual import incidence_dual
        source = regular('great-dodecahedron')
        polar = incidence_dual(source)
        result = assemble([source, polar]); evidence = {'method':'ordered incidence polar at origin, radius 1', 'contactClaim':False}
    else:
        _, _, seed, orbit, count, _, chirality = next(r for r in ENTRIES if key=='compound-'+r[0])
        if seed in ('tetrahedron', 'truncated-tetrahedron'):
            source = regular('tetrahedron')
            target = np.asarray([v for v in product((-1,1), repeat=3) if np.prod(v)>0])
            alignment = np.linalg.solve(np.asarray(source['vertices'])[:3], target[:3]).T
            source = moved(source, alignment)
            if seed.startswith('truncated'):
                from .operations import truncate
                source = truncate(source)
        else: source = regular(seed)
        initial = np.eye(3)
        if orbit == 'O-edge': initial = rotation([0,0,1], math.pi/4)
        if orbit == 'O-triad': initial = rotation([1,1,1], math.pi/3)
        if orbit == 'I-swapped': initial = rotation([0,0,1], math.pi/2)
        if orbit == 'I-mirror': initial = -np.eye(3)
        group_name = 'O' if orbit.startswith('O-') else 'I' if orbit in ('I-swapped','I-mirror') else orbit
        group = (np.eye(3),-np.eye(3)) if orbit=='inversion' else symmetry_group(group_name)
        models, transforms = orbit_models(source, [g @ initial for g in group], count)
        result = assemble(models)
        evidence = {'group':group_name, 'groupOrder':len(group), 'componentMatrices':transforms,
                    'closureVerified':True, 'symmetryScope':'declared finite generating group; no maximality claim',
                    'orientation':'signed-coordinate Platonic seed; Rodrigues rotations and finite group cosets',
                    'enantiomorph':chirality}
    actual = [len(result[k]) for k in ('vertices','edges','faces','cells')]
    if actual != entry['counts'] or len(result['components']) != entry['componentCount']:
        raise GeometryError('Compound catalog incidence does not match its declared counts.')
    result['name'] = entry['name']
    for i,c in enumerate(result['components']):c['name'] = f'{i+1}: '+c['name']
    result['metadata'].update(deepcopy(entry))
    result['metadata']['compoundSymmetry'] = {**evidence, 'certified':False, 'coordinateTolerance':1e-7}
    result['provenance'].update(catalogKey=key, generation='generated by symmetry', algorithmVersion=VERSION)
    result['fingerprint'] = identity(result)
    result['validation'] = validate(result)
    return result
